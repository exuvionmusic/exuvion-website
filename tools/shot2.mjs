import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath:"C:/Program Files/Google/Chrome/Application/chrome.exe", headless:"new", args:["--hide-scrollbars"] });
const shoot = async (name,w,h,y) => {
  const p = await b.newPage();
  await p.setViewport({width:w,height:h});
  await p.goto("http://localhost:3100/", { waitUntil:"networkidle0" });
  await p.evaluate(()=>document.querySelectorAll(".reveal").forEach(n=>n.setAttribute("data-shown","true")));
  await p.evaluate(yy=>window.scrollTo(0,yy), y);
  await new Promise(r=>setTimeout(r,1200));
  await p.screenshot({path:`tools/shots/${name}.png`});
  await p.close();
};
const p = await b.newPage();
await p.setViewport({width:1440,height:900});
await p.goto("http://localhost:3100/", { waitUntil:"networkidle0" });
await p.evaluate(()=>document.querySelectorAll(".reveal").forEach(n=>n.setAttribute("data-shown","true")));
const y = await p.evaluate(()=>document.querySelector(".photoband").getBoundingClientRect().top + window.scrollY - 220);
await p.close();
await shoot("photoband",1440,900,y);
await b.close();
